#!/usr/bin/env python3
"""
OpenMPI eager/rendezvous 阈值的约束和可设置范围
"""

print("=" * 70)
print("OpenMPI 协议阈值的约束")
print("=" * 70)
print()

print("理论上，环境变量是字符串，可以设置任意数值，但OpenMPI内部有约束：")
print()

print("1. 最小值约束:")
print("   - OMPI_MCA_btl_vader_eager_limit (共享内存传输):")
print("     • 最小值: 通常 >= 1 byte")
print("     • 推荐: >= 256 byte（避免过多拷贝开销）")
print()
print("   - OMPI_MCA_btl_tcp_eager_limit (TCP网络传输):")
print("     • 最小值: 通常 >= 1 byte")
print("     • 推荐: >= 1 KB（否则网络开销很大）")
print()

print("2. 最大值约束:")
print("   - 没有硬性最大值限制")
print("   - 但设置过大可能无意义")
print("     • 例如设置10GB → 几乎所有消息都用eager")
print("     • 可能导致缓冲区溢出或内存不足")
print()

print("3. 实际可设置的常见值:")
print()
print("   ┌─────────────────┬──────────┬─────────────────────────┐")
print("   │ 阈值            │ 字节数   │ 说明                    │")
print("   ├─────────────────┼──────────┼─────────────────────────┤")
print("   │ 1               │ 1        │ 强制rendezvous          │")
print("   │ 1024            │ 1 KB     │ 非常小的消息用eager     │")
print("   │ 65536           │ 64 KB    │ 较小消息用eager         │")
print("   │ 262144          │ 256 KB   │ OpenMPI默认阈值         │")
print("   │ 1048576         │ 1 MB     │ 1MB以下用eager          │")
print("   │ 4194304         │ 4 MB     │ 类似IntelMPI             │")
print("   │ 16777216        │ 16 MB    │ 很大的消息也用eager     │")
print("   └─────────────────┴──────────┴─────────────────────────┘")
print()

print("4. OpenMPI设置示例:")
print()
print("   a) 完全禁用eager（强制rendezvous）:")
print("      export OMPI_MCA_btl_vader_eager_limit=1")
print("      export OMPI_MCA_btl_tcp_eager_limit=1")
print()
print("   b) 激进eager（小消息都用eager）:")
print("      export OMPI_MCA_btl_vader_eager_limit=4194304      # 4 MB")
print("      export OMPI_MCA_btl_tcp_eager_limit=4194304")
print()
print("   c) 自定义阈值（例如1MB）:")
print("      export OMPI_MCA_btl_vader_eager_limit=1048576      # 1 MB")
print("      export OMPI_MCA_btl_tcp_eager_limit=1048576")
print()
print("   d) 很激进（几乎全用eager）:")
print("      export OMPI_MCA_btl_vader_eager_limit=268435456    # 256 MB")
print("      export OMPI_MCA_btl_tcp_eager_limit=268435456")
print()

print("5. vader vs tcp 的区别:")
print()
print("   - vader_eager_limit: 适用于共享内存通信（intra-node）")
print("     • 成本低，可以用较高阈值")
print()
print("   - tcp_eager_limit: 适用于网络通信（inter-node）")
print("     • 成本高，应该用较低阈值")
print("     • 例如: vader=4MB, tcp=256KB")
print()

print("6. 测试不同阈值:")
print()
print("   #!/bin/bash")
print("   for threshold in 1 65536 262144 1048576 4194304; do")
print("       export OMPI_MCA_btl_vader_eager_limit=$threshold")
print("       export OMPI_MCA_btl_tcp_eager_limit=$threshold")
print("       echo \"Testing with threshold=$threshold bytes\"")
print("       mpirun -n 4 ./comb 128_128_128 -divide 2_2_1 ...")
print("   done")
print()

print("=" * 70)
print("建议")
print("=" * 70)
print()
print("1. 不要随意设置，除非你知道为什么")
print("2. 常见策略:")
print("   - 保守: vader=256KB, tcp=64KB（倾向rendezvous）")
print("   - 默认: vader=256KB, tcp=256KB（均衡）")
print("   - 激进: vader=4MB, tcp=1MB（倾向eager）")
print("3. 对于小消息实验，才考虑改阈值")
print()
